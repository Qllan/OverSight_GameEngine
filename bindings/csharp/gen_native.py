"""Regenerates ORST/Native.cs (P/Invoke declarations) from orst.h.

Run after adding or changing a function in the header:
    python bindings/csharp/gen_native.py
Types the script does not know stop it with an error, so a new struct or
pointer type gets a mapping here first.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = os.path.join(HERE, "..", "..", "crates", "orst", "include", "orst.h")
OUT = os.path.join(HERE, "ORST", "Native.cs")

# C value types -> C# types
VALUES = {
    "void": "void", "bool": "bool", "float": "float", "double": "double",
    "uint32_t": "uint", "int32_t": "int", "uint64_t": "ulong", "int64_t": "long", "size_t": "nuint",
    "OrstColor": "Color", "OrstVec2": "Vec2", "OrstRect": "Rect", "OrstCamera": "Camera", "OrstTransform": "Transform",
    "OrstSpriteSheet": "SpriteSheet", "OrstMoveResult": "MoveResult", "OrstContacts": "Contacts",
    "OrstEmitter": "EmitterConfig", "OrstEntity": "ulong", "OrstBinding": "Binding",
}
# C pointer parameters -> C# parameters
POINTERS = {
    "OrstEngine": "IntPtr", "const OrstConfig": "in NativeConfig", "const OrstSprite": "in Sprite",
    "const OrstSpriteSheet": "in SpriteSheet", "const OrstEmitter": "in EmitterConfig",
    "uint32_t": "out uint", "float": "out float",
    "OrstTilemapInfo": "out TilemapInfo", "OrstMapObject": "out MapObjectData", "OrstRayHit": "out RayHit",
    "const uint8_t": "byte[]", "const uint32_t": "uint[]", "char": "[In, Out] byte[]?",
    "const void": "IntPtr", "OrstEntity": "[In, Out] ulong[]?", "uint8_t": "[In, Out] byte[]?", "OrstBinding": "out Binding",
    "const OrstVec2": "Vec2[]", "OrstOverlap": "out Overlap", "OrstContact": "out Contact", "OrstVec2": "[In, Out] Vec2[]?", "OrstEntityHit": "out EntityHit",
    "const OrstCamera": "Camera[]?", "const OrstEffect": "Effect[]?",
    "const OrstField": "NativeField[]", "OrstField": "out NativeField",
}
KEYWORDS = {"base", "in", "out", "string", "object", "params", "fixed", "event", "lock"}

PRELUDE = """// P/Invoke declarations for orst.h. Generated by gen_native.py from
// the header: edit the header, then run the script.
using System.Runtime.InteropServices;

namespace ORST;

[StructLayout(LayoutKind.Sequential)]
internal struct NativeConfig
{
    public IntPtr Title;
    public uint Width, Height;
    public float Scale;
    public byte Resizable, Fullscreen, IntegerScale;
    public uint TargetFps;
    public byte Headless;
    public int Renderer;
}

[StructLayout(LayoutKind.Sequential)]
internal struct MapObjectData
{
    public uint Id;
    public Rect Rect;
    public byte Point, Visible;
    public float Rotation;
    public uint Gid, Layer;
}

[StructLayout(LayoutKind.Sequential)]
internal struct NativeField
{
    public IntPtr Name;
    public uint Type, Offset, Flags;
    public float Min, Max;
    public IntPtr Options;
}

internal static class Native
{
    private const string Lib = "orst";

"""


def param(p):
    m = re.match(r"(.*?)\s*(\*?)\s*(\w+)$", p.strip())
    ctype, star, name = m.group(1).strip(), m.group(2), m.group(3)
    if name in KEYWORDS:
        name = "@" + name
    if star:
        cs = "[MarshalAs(UnmanagedType.LPUTF8Str)] string" if ctype == "const char" else POINTERS[ctype]
    else:
        cs = VALUES[ctype]
        if cs == "bool":
            cs = "[MarshalAs(UnmanagedType.U1)] bool"
    return f"{cs} {name}"


def main():
    header = open(HEADER, encoding="utf-8").read()
    body = header[header.index("/* --- engine and frame --- */"):]
    decls = re.findall(r"^([A-Za-z_][\w \*]*?)\s*(\*?)(orst_\w+)\((.*?)\);", body, re.S | re.M)
    lines = []
    for ret, star, name, params in decls:
        ret = ret.strip()
        params = " ".join(params.split())
        cs_ret = "IntPtr" if star or ret.endswith("*") else VALUES[ret]
        attr = "[return: MarshalAs(UnmanagedType.U1)] " if cs_ret == "bool" else ""
        args = [] if params in ("", "void") else [param(p) for p in params.split(",")]
        lines.append(f"    [DllImport(Lib)] {attr}internal static extern {cs_ret} {name}({', '.join(args)});")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(PRELUDE + "\n".join(lines) + "\n}\n")
    print(f"{len(lines)} functions -> {OUT}")


if __name__ == "__main__":
    main()
